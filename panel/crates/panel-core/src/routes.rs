impl RouteId {
    /// The table row for this identifier.
    ///
    /// The panic is unreachable: `route_table_covers_every_route_id_exactly_once`
    /// guarantees every variant is present in `ROUTE_TABLE`.
    pub fn spec(self) -> &'static RouteSpec {
        ROUTE_TABLE
            .iter()
            .find(|spec| spec.id == self)
            .expect("ROUTE_TABLE covers every RouteId")
    }

    /// `"POST /api/nodes/{node_id}/auth/rotate"`, for documents that reference a
    /// route as text. Written from here rather than as a literal, otherwise such
    /// a document drifts from the router exactly as the contract's route list
    /// used to.
    pub fn endpoint_label(self) -> String {
        let spec = self.spec();
        format!("{} {}", spec.method.as_str(), spec.path)
    }
}

/// Routes with a given trust boundary, in table order.
pub fn routes_with_exposure(exposure: RouteExposure) -> impl Iterator<Item = &'static RouteSpec> {
    ROUTE_TABLE
        .iter()
        .filter(move |spec| spec.exposure == exposure)
}

/// The browser surface: exactly what the admin UI calls.
pub fn admin_ui_routes() -> impl Iterator<Item = &'static RouteSpec> {
    routes_with_exposure(RouteExposure::AdminUi)
}

/// Groups in order of first appearance, with their routes.
pub fn admin_ui_routes_by_group() -> Vec<(RouteGroup, Vec<&'static RouteSpec>)> {
    let mut grouped: Vec<(RouteGroup, Vec<&'static RouteSpec>)> = Vec::new();
    for spec in admin_ui_routes() {
        match grouped.iter_mut().find(|(group, _)| *group == spec.group) {
            Some((_, specs)) => specs.push(spec),
            None => grouped.push((spec.group, vec![spec])),
        }
    }
    grouped
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn route_table_covers_every_route_id_exactly_once() {
        let mut seen: Vec<RouteId> = ROUTE_TABLE.iter().map(|spec| spec.id).collect();
        assert_eq!(
            seen.len(),
            RouteId::ALL.len(),
            "ROUTE_TABLE has {} rows while RouteId has {} variants",
            seen.len(),
            RouteId::ALL.len()
        );
        for id in RouteId::ALL {
            let position = seen.iter().position(|candidate| candidate == id);
            match position {
                Some(index) => {
                    seen.remove(index);
                }
                None => panic!("{id:?} is declared in RouteId but absent from ROUTE_TABLE"),
            }
        }
        assert!(seen.is_empty(), "ROUTE_TABLE has surplus rows: {seen:?}");
    }

    #[test]
    fn route_table_has_no_duplicate_method_and_path() {
        let mut pairs = HashSet::new();
        for spec in ROUTE_TABLE {
            assert!(
                pairs.insert((spec.method, spec.path)),
                "duplicate {} {}: axum panics while building the router",
                spec.method.as_str(),
                spec.path
            );
        }
    }

    #[test]
    fn admin_ui_surface_excludes_node_agent_and_executor_routes() {
        for spec in admin_ui_routes() {
            assert!(
                !spec.path.starts_with("/api/node-agent/"),
                "{} leaked into the browser surface",
                spec.path
            );
        }
        let exposures: HashSet<RouteExposure> =
            admin_ui_routes().map(|spec| spec.exposure).collect();
        assert_eq!(
            exposures,
            HashSet::from([RouteExposure::AdminUi]),
            "the exposure filter let a foreign trust boundary through"
        );
    }

    #[test]
    fn every_node_agent_path_is_declared_as_node_agent_exposure() {
        for spec in ROUTE_TABLE {
            if spec.path.starts_with("/api/node-agent/") {
                assert_eq!(
                    spec.exposure,
                    RouteExposure::NodeAgent,
                    "{} serves the agent but is declared as {}",
                    spec.path,
                    spec.exposure.as_str()
                );
            }
        }
    }

    #[test]
    fn paginated_routes_are_read_only() {
        for spec in ROUTE_TABLE {
            if spec.paginated {
                assert_eq!(
                    spec.method,
                    RouteMethod::Get,
                    "{} is marked paginated but is not a read",
                    spec.path
                );
            }
        }
    }
}
