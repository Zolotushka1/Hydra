/// Trust boundary: who may call a route and what they authenticate with.
///
/// - `AdminUi`   — an admin session (`authorize`); this is the browser surface;
/// - `NodeAgent` — a node token in the `x-hydra-node-token` header;
/// - `Executor`  — a provisioning or installer executor token, in a header or body;
/// - `Public`    — no authentication, reachable from the internet;
/// - `Debug`     — diagnostic; must not exist in a production build.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RouteExposure {
    AdminUi,
    NodeAgent,
    Executor,
    Public,
    Debug,
}

impl RouteExposure {
    pub const ALL: &'static [Self] = &[
        Self::AdminUi,
        Self::NodeAgent,
        Self::Executor,
        Self::Public,
        Self::Debug,
    ];

    pub const fn as_str(self) -> &'static str {
        match self {
            Self::AdminUi => "admin_ui",
            Self::NodeAgent => "node_agent",
            Self::Executor => "executor",
            Self::Public => "public",
            Self::Debug => "debug",
        }
    }
}

