//! The single source of truth for the panel's HTTP surface.
//!
//! `ROUTE_TABLE` describes every method+path pair exactly once. The axum router
//! in `panel-app` is built from it, and the `GET /api/ui/contracts` document is
//! generated from it. There is no second route list in the project, so a
//! divergence between what is served and what is advertised to the frontend has
//! nowhere to be expressed.
//!
//! Adding a route takes three edits: a new `RouteId` variant, a `ROUTE_TABLE`
//! row, and an arm in `method_router` (panel-app). Skipping any of them is a
//! compile error or a failing test, never a silent drift.
//!
//! `exposure` is a trust boundary, not decoration. It is assigned from the
//! authentication a route actually enforces, never from its path prefix:
//! `/api/installer/jobs/result` sits in the `Installer` group but authenticates
//! with an executor token in the request body, so its exposure is `Executor` and
//! it stays out of the browser contract.

use serde::{Deserialize, Serialize};

/// HTTP method. A local type so `panel-core` does not depend on axum or http:
/// the core stays transport-agnostic and the mapping lives in `panel-app`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "UPPERCASE")]
pub enum RouteMethod {
    Get,
    Post,
    Put,
    Delete,
}

impl RouteMethod {
    pub const ALL: &'static [Self] = &[Self::Get, Self::Post, Self::Put, Self::Delete];

    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Get => "GET",
            Self::Post => "POST",
            Self::Put => "PUT",
            Self::Delete => "DELETE",
        }
    }
}

